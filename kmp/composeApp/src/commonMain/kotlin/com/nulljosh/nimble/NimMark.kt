// Nim, drawn from the same SVG the web uses (NimArt.kt is generated by scripts/nim-poses.py). Android has no SVG
// decoder, so this reads the small subset those files use: g (rotate, clip), circle, rect, path.
private class SvgNode(val tag: String, val attrs: Map<String, String>) {
    val kids = mutableListOf<SvgNode>()
    val path: Path? by lazy { attrs["d"]?.let { PathParser().parsePathString(it).toPath() } }
}

private val tagRe = Regex("""<(/?)([a-zA-Z]+)([^>]*?)(/?)>""")
private val attrRe = Regex("""([a-zA-Z-]+)="([^"]*)"""")
private val commentRe = Regex("""<!--.*?-->""", RegexOption.DOT_MATCHES_ALL)

private fun parseSvg(svg: String): SvgNode {
    val root = SvgNode("root", emptyMap())
    val open = ArrayDeque<SvgNode>().apply { addLast(root) }
    for (m in tagRe.findAll(svg.replace(commentRe, ""))) {
        val (close, tag, rest, self) = m.destructured
        if (close == "/") { if (open.size > 1) open.removeLast(); continue }
        val node = SvgNode(tag, attrRe.findAll(rest).associate { it.groupValues[1] to it.groupValues[2] })
        open.last().kids.add(node)
        if (self != "/") open.addLast(node)
    }
    return root
}

private fun color(css: String?, opacity: Float): Color? {
    if (css == null || css == "none" || !css.startsWith("#")) return null
    val hex = css.drop(1).let { if (it.length == 3) it.map { c -> "$c$c" }.joinToString("") else it }
    val rgb = hex.toLongOrNull(16) ?: return null
    return Color((0xFF000000 or rgb).toInt()).copy(alpha = opacity)
}

private fun findById(n: SvgNode, id: String): SvgNode? =
    if (n.attrs["id"] == id) n else n.kids.firstNotNullOfOrNull { findById(it, id) }

private val rotateRe = Regex("""rotate\((-?[\d.]+) ([\d.]+) ([\d.]+)\)""")
private val urlRe = Regex("""#([\w-]+)""")

private fun DrawScope.drawNode(n: SvgNode, root: SvgNode) {
    when (n.tag) {
        "root", "svg", "g" -> {
            var run: DrawScope.() -> Unit = { n.kids.forEach { drawNode(it, root) } }
            rotateRe.find(n.attrs["transform"] ?: "")?.let { r ->
                val inner = run
                run = { rotate(r.groupValues[1].toFloat(), Offset(r.groupValues[2].toFloat(), r.groupValues[3].toFloat())) { inner() } }
            }
            n.attrs["clip-path"]?.let { urlRe.find(it)?.groupValues?.get(1) }?.let { id ->
                val c = findById(root, id)?.kids?.firstOrNull { it.tag == "circle" }
                if (c != null) {
                    val clip = Path().apply {
                        addOval(androidx.compose.ui.geometry.Rect(Offset(c.f("cx"), c.f("cy")), c.f("r")))
                    }
                    val inner = run
                    run = { clipPath(clip) { inner() } }
                }
            }
            run()
        }
        "circle" -> {
            val centre = Offset(n.f("cx"), n.f("cy"))
            fill(n)?.let { drawCircle(it, n.f("r"), centre) }
            stroke(n)?.let { drawCircle(it, n.f("r"), centre, style = strokeStyle(n)) }
        }
        "rect" -> {
            val at = Offset(n.f("x"), n.f("y"))
            val size = Size(n.f("width"), n.f("height"))
            fill(n)?.let { drawRoundRect(it, at, size, CornerRadius(n.f("rx"))) }
        }
        "path" -> n.path?.let { p ->
            fill(n)?.let { drawPath(p, it) }
            stroke(n)?.let { drawPath(p, it, style = strokeStyle(n)) }
        }
    }
}

private fun SvgNode.f(key: String) = attrs[key]?.toFloatOrNull() ?: 0f
private fun opacity(n: SvgNode) = n.attrs["opacity"]?.toFloatOrNull() ?: 1f
// An element with a stroke and no fill attribute is a line, not a black shape.
private fun fill(n: SvgNode) = color(n.attrs["fill"] ?: if (n.attrs.containsKey("stroke")) null else "#000000", opacity(n))
private fun stroke(n: SvgNode) = color(n.attrs["stroke"], opacity(n))
private fun strokeStyle(n: SvgNode) = Stroke(
    width = n.f("stroke-width").takeIf { it > 0f } ?: 1f,
    cap = if (n.attrs["stroke-linecap"] == "round") StrokeCap.Round else StrokeCap.Butt,
    join = if (n.attrs["stroke-linejoin"] == "round") StrokeJoin.Round else StrokeJoin.Miter,
)

/** One of Nim's poses: wave, think, cheer or doze, on its yellow disc. Decorative, so no description. */
@Composable
fun NimMark(pose: String, size: Dp, modifier: Modifier = Modifier) {
    val root = remember(pose) { NIM_ART[pose]?.let(::parseSvg) } ?: return
    Canvas(modifier.size(size)) {
        scale(this.size.width / 240f, Offset.Zero) { drawNode(root, root) }
    }
}
