#!/usr/bin/env python3
"""Draws the mascot, the Nimble lightbulb from the app icon, in four poses: docs/mascot/nim-{wave,think,cheer,doze}.svg.
Every pose is the same bulb on a brand-yellow disc (so it holds up on dark backgrounds); only the eyes, the mouth,
the arms and the glow change. Run: python3 scripts/nim-poses.py
ponytail: files keep the old nim-* names so every page, test and asset catalog that loads them keeps working."""
from pathlib import Path

INK, YELLOW, DEEP, LIT, DIM, CHEEK = "#2a1a12", "#ffca30", "#8a6412", "#ffffff", "#fff3cf", "#e07a3f"

def glass(fill):
    """The bulb: round glass, a tapered neck, then the screw base in three bands."""
    return f'''<circle cx="120" cy="100" r="62" fill="{fill}"/>
  <path d="M86 140 L 154 140 L 144 182 L 96 182 Z" fill="{fill}"/>
  <rect x="96" y="184" width="48" height="13" rx="5" fill="{DEEP}"/>
  <rect x="100" y="199" width="40" height="13" rx="5" fill="{DEEP}"/>
  <rect x="110" y="214" width="20" height="9" rx="4" fill="{DEEP}"/>
  <circle cx="98" cy="120" r="8" fill="{CHEEK}" opacity="0.28"/>
  <circle cx="142" cy="120" r="8" fill="{CHEEK}" opacity="0.28"/>'''

def open_eyes(dx=0, dy=0, cls=""):
    c = f' class="{cls}"' if cls else ""
    return f'''<g{c}><circle cx="{102+dx}" cy="{100+dy}" r="9" fill="{INK}"/>
  <circle cx="{138+dx}" cy="{100+dy}" r="9" fill="{INK}"/>
  <circle cx="{105+dx}" cy="{97+dy}" r="3" fill="#fff"/>
  <circle cx="{141+dx}" cy="{97+dy}" r="3" fill="#fff"/></g>'''

# Happy closed eyes curve up; sleeping ones curve down.
HAPPY = f'''<path d="M92 104 Q 102 92 112 104" fill="none" stroke="{INK}" stroke-width="4.5" stroke-linecap="round"/>
  <path d="M128 104 Q 138 92 148 104" fill="none" stroke="{INK}" stroke-width="4.5" stroke-linecap="round"/>'''
ASLEEP = f'''<path d="M92 100 Q 102 110 112 100" fill="none" stroke="{INK}" stroke-width="4.5" stroke-linecap="round"/>
  <path d="M128 100 Q 138 110 148 100" fill="none" stroke="{INK}" stroke-width="4.5" stroke-linecap="round"/>'''

SMILE = f'<path d="M106 122 Q 120 140 134 122 Z" fill="{INK}"/>'
GRIN = f'<path d="M102 120 Q 120 146 138 120 Z" fill="{INK}"/>'
PURSE = f'<circle cx="126" cy="128" r="4.5" fill="{INK}"/>'
REST = f'<path d="M112 128 Q 120 132 128 128" fill="none" stroke="{INK}" stroke-width="4" stroke-linecap="round"/>'

def arm(x0, y0, x1, y1):
    """A thin wire arm from the glass to a round hand."""
    return f'''<path d="M{x0} {y0} L {x1} {y1}" stroke="{DEEP}" stroke-width="6" stroke-linecap="round"/>
  <circle cx="{x1}" cy="{y1}" r="9" fill="{DEEP}"/>'''

RAYS = "".join(
    f'<path d="M{ax} {ay} L {bx} {by}" stroke="#fff" stroke-width="6" stroke-linecap="round"/>'
    for ax, ay, bx, by in [(120, 26, 120, 12), (64, 46, 54, 36), (176, 46, 186, 36), (44, 100, 30, 100), (196, 100, 210, 100)])
ZZZ = f'<path d="M168 44 L 184 44 L 168 60 L 184 60" fill="none" stroke="{DEEP}" stroke-width="4" stroke-linecap="round" stroke-linejoin="round"/>'

POSES = {
    # Hello: the empty screen. One arm down, one waving.
    "wave": dict(fill=LIT, eyes=open_eyes(), mouth=SMILE, extra=arm(62, 120, 42, 152) + arm(178, 110, 204, 72)),
    # Thinking: the loading card. Eyes up and aside, glass not lit yet, a hand at the chin.
    "think": dict(fill=DIM, eyes=open_eyes(-3, -4, "nim-eye"), mouth=PURSE, extra=arm(62, 120, 42, 152) + arm(170, 132, 146, 150)),
    # Got it: lit, rays out, both arms up.
    "cheer": dict(fill=LIT, eyes=HAPPY, mouth=GRIN, extra=RAYS + arm(62, 110, 36, 72) + arm(178, 110, 204, 72)),
    # Resting: the free AI is out for the day. Tilted, dim, eyes shut.
    "doze": dict(fill=DIM, eyes=ASLEEP, mouth=REST, extra=ZZZ, tilt=-8),
}

def svg(pose, p):
    tilt = p.get("tilt", 0)
    head = f'<g transform="rotate({tilt} 120 150)">' if tilt else "<g>"
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 240 240" role="img" aria-label="The Nimble lightbulb, the mascot">
  <!-- Generated by scripts/nim-poses.py ({pose}). Edit the script, not this file. -->
  <defs><clipPath id="nim-disc-{pose}"><circle cx="120" cy="120" r="120"/></clipPath></defs>
  <circle cx="120" cy="120" r="120" fill="{YELLOW}"/>
  <g clip-path="url(#nim-disc-{pose})">
  {head}{glass(p["fill"])}
  {p["eyes"]}
  {p["mouth"]}
  {p["extra"]}</g>
  </g>
</svg>
'''

out = Path(__file__).resolve().parent.parent / "docs" / "mascot"
for name, p in POSES.items():
    (out / f"nim-{name}.svg").write_text(svg(name, p))
(out / "nim.svg").write_text(svg("wave", POSES["wave"]))

# The same drawings for the Kotlin apps, which draw them with NimMark.kt (no SVG support on Android).
kt = out.parent.parent / "kmp" / "composeApp" / "src" / "commonMain" / "kotlin" / "com" / "nulljosh" / "nimble" / "NimArt.kt"
body = "".join(f'    "{n}" to """{(out / f"nim-{n}.svg").read_text()}""",\n' for n in POSES)
kt.write_text("package com.nulljosh.nimble\n\n// Generated by scripts/nim-poses.py. Edit the script, not this file.\ninternal val NIM_ART: Map<String, String> = mapOf(\n" + body + ")\n")
print("wrote", ", ".join(f"nim-{n}.svg" for n in POSES), "nim.svg and NimArt.kt")
